package rabbitmq

import (
	"context"
	"encoding/json"
	"fmt"
	"log"

	"github.com/google/uuid"
	amqp "github.com/rabbitmq/amqp091-go"
)

var (
	conn    *amqp.Connection
	channel *amqp.Channel
)

func ConnectRabbitMQ(url string) {
	var err error
	conn, err = amqp.Dial(url)
	if err != nil {
		log.Fatalf("Failed to connect to RabbitMQ: %v", err)
	}

	channel, err = conn.Channel()
	if err != nil {
		log.Fatalf("Failed to open a channel: %v", err)
	}
	
	// Setup DLQ (Dead Letter Queue) & Main Queue
	setupQueues()
	
	log.Println("Successfully connected to RabbitMQ (Golang API) with DLQ support")
}

func setupQueues() {
	// Declare DLX
	err := channel.ExchangeDeclare("dlx", "direct", true, false, false, false, nil)
	if err != nil {
		log.Printf("Warning: Failed to declare DLX: %v", err)
	}
	
	// Declare DLQ
	_, err = channel.QueueDeclare("geometry_tasks_dlq", true, false, false, false, nil)
	if err == nil {
		channel.QueueBind("geometry_tasks_dlq", "geometry_tasks", "dlx", false, nil)
	}

	// Declare main queue with DLX
	args := amqp.Table{
		"x-dead-letter-exchange": "dlx",
		"x-message-ttl":          int32(60000), // 60s timeout then DLQ
	}
	_, err = channel.QueueDeclare("geometry_tasks", true, false, false, false, args)
	if err != nil {
		log.Printf("Warning: Failed to declare geometry_tasks queue: %v", err)
	}
}

func GetChannel() *amqp.Channel {
	return channel
}

func CloseRabbitMQ() {
	if channel != nil {
		channel.Close()
	}
	if conn != nil {
		conn.Close()
	}
}

// ConnectionStatus returns "Online" if RabbitMQ connection is active, otherwise "Disconnected"
func ConnectionStatus() string {
	if conn == nil || conn.IsClosed() {
		return "Disconnected"
	}
	return "Online"
}

// PublishRPC sends a message and waits for a response with a timeout
func PublishRPC(ctx context.Context, queueName string, task string, payload interface{}) (string, error) {
	// 1. Declare an exclusive callback queue
	q, err := channel.QueueDeclare(
		"",    // name generated by RabbitMQ
		false, // durable
		false, // delete when unused
		true,  // exclusive
		false, // noWait
		nil,   // arguments
	)
	if err != nil {
		return "", fmt.Errorf("failed to declare a callback queue: %w", err)
	}

	msgs, err := channel.Consume(
		q.Name, // queue
		"",     // consumer
		true,   // auto-ack
		false,  // exclusive
		false,  // no-local
		false,  // no-wait
		nil,    // args
	)
	if err != nil {
		return "", fmt.Errorf("failed to register a consumer: %w", err)
	}

	// 2. Generate a unique correlation ID
	corrId := uuid.New().String()

	// 3. Prepare the message payload
	body, err := json.Marshal(map[string]interface{}{
		"task":    task,
		"payload": payload,
	})
	if err != nil {
		return "", fmt.Errorf("failed to marshal payload: %w", err)
	}

	// 4. Publish the message
	err = channel.PublishWithContext(ctx,
		"",        // exchange
		queueName, // routing key
		false,     // mandatory
		false,     // immediate
		amqp.Publishing{
			ContentType:   "application/json",
			CorrelationId: corrId,
			ReplyTo:       q.Name,
			Body:          body,
		})
	if err != nil {
		return "", fmt.Errorf("failed to publish a message: %w", err)
	}

	// 5. Wait for the response or timeout
	for {
		select {
		case <-ctx.Done():
			return "", fmt.Errorf("rpc request timeout: %w", ctx.Err())
		case d := <-msgs:
			if d.CorrelationId == corrId {
				return string(d.Body), nil
			}
		}
	}
}
